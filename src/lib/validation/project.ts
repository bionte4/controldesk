import { z } from "zod";

import { uuidSchema } from "./common";

/**
 * Zod schemas for the projects module (rules §7).
 *
 * Aligned with:
 *   - supabase/migrations/0008_clients_and_projects.sql (base table)
 *   - supabase/migrations/0022_projects_gas_align.sql   (project_type, milestones)
 *   - supabase/migrations/0036_projects_wizard_fields.sql (priority, DRAFT,
 *     location, contract_value, currency, notes, sync_calendar, auto-number)
 */

// ---------------------------------------------------------------------------
// Enums (kept in sync with database enums).
// ---------------------------------------------------------------------------

export const PROJECT_STATUSES = [
  "DRAFT",
  "PLANNING",
  "ACTIVE",
  "ON_HOLD",
  "COMPLETED",
  "ARCHIVED",
] as const;
export const projectStatusSchema = z.enum(PROJECT_STATUSES);
export type ProjectStatus = z.infer<typeof projectStatusSchema>;

export const PROJECT_PRIORITIES = ["CRITICAL", "HIGH", "MEDIUM", "LOW"] as const;
export const projectPrioritySchema = z.enum(PROJECT_PRIORITIES);
export type ProjectPriority = z.infer<typeof projectPrioritySchema>;

export const PROJECT_TYPES = [
  "FIXED_PRICE",
  "TIME_MATERIAL",
  "RETAINER",
  "INTERNAL",
] as const;
export const projectTypeSchema = z.enum(PROJECT_TYPES);
export type ProjectTypeValue = z.infer<typeof projectTypeSchema>;

const MILESTONE_STATUSES = [
  "PLANNED",
  "IN_PROGRESS",
  "AT_RISK",
  "DONE",
  "CANCELLED",
] as const;
export const milestoneStatusSchema = z.enum(MILESTONE_STATUSES);

const projectCode = z
  .string()
  .trim()
  .min(2, "Project code must be at least 2 characters.")
  .max(32, "Project code is too long.")
  .regex(
    /^[A-Z0-9][A-Z0-9-]*$/i,
    "Only letters, digits, and dashes are allowed.",
  );

const isoDateSchema = z
  .string()
  .trim()
  .regex(/^\d{4}-\d{2}-\d{2}$/, "Must be an ISO date (YYYY-MM-DD).");

// ---------------------------------------------------------------------------
// Inline milestone rows for the wizard's Step 3.
// weight_bps stays in basis points (0-10000) to avoid float rounding —
// UI collects percent (0-100) and the action converts × 100.
// ---------------------------------------------------------------------------

export const wizardMilestoneSchema = z
  .object({
    name: z.string().trim().min(1, "Milestone name is required.").max(160),
    due_date: isoDateSchema.optional(),
    weight_pct: z
      .number({ message: "Weight must be a number." })
      .int("Weight must be a whole number.")
      .min(0, "Weight cannot be negative.")
      .max(100, "Weight cannot exceed 100."),
  })
  .strict();
export type WizardMilestoneInput = z.infer<typeof wizardMilestoneSchema>;

// ---------------------------------------------------------------------------
// Create project (wizard-driven).
// ---------------------------------------------------------------------------

const projectBaseSchema = z.object({
  // Step 1 — Info
  client_id: uuidSchema,
  contract_id: uuidSchema.optional(),
  code: projectCode.optional(), // Auto-generated by DB trigger if omitted
  name: z.string().trim().min(2, "Name is too short.").max(160),
  description: z
    .string()
    .trim()
    .max(2000)
    .optional()
    .transform((v) => (v ? v : undefined)),
  status: projectStatusSchema.default("DRAFT"),
  priority: projectPrioritySchema.default("MEDIUM"),
  project_type: projectTypeSchema,
  location: z
    .string()
    .trim()
    .max(120, "Location is too long.")
    .optional()
    .transform((v) => (v ? v : undefined)),
  pm_employee_id: uuidSchema.optional(),

  // Step 2 — Timeline & budget
  start_date: isoDateSchema.optional(),
  end_date: isoDateSchema.optional(),
  contract_value_idr: z
    .number({ message: "Contract value must be a number." })
    .int("Contract value must be a whole rupiah amount.")
    .nonnegative("Contract value cannot be negative.")
    .optional(),
  currency: z
    .string()
    .trim()
    .length(3, "Currency must be a 3-letter code.")
    .default("IDR"),
  notes: z
    .string()
    .trim()
    .max(2000)
    .optional()
    .transform((v) => (v ? v : undefined)),
  sync_calendar: z.boolean().default(false),

  // Business Case fields (migration 0058). Optional at creation; the
  // project starts in DRAFT (BC intake) and can be edited later. All
  // three are informational — approval / status transition is a
  // separate action.
  bc_executive_summary: z
    .string()
    .trim()
    .max(4000)
    .optional()
    .transform((v) => (v ? v : undefined)),
  bc_target_gm_pct: z
    .number({ message: "Target margin must be a number." })
    .min(0, "Target margin cannot be negative.")
    .max(100, "Target margin cannot exceed 100.")
    .optional(),
  bc_sponsor_id: uuidSchema.optional(),

  // Step 3 — Milestones (optional at creation)
  milestones: z.array(wizardMilestoneSchema).max(50).default([]),
});

export const createProjectSchema = projectBaseSchema
  .refine(
    (v) => !v.end_date || !v.start_date || v.end_date >= v.start_date,
    { path: ["end_date"], message: "End date must be on or after start date." },
  )
  .refine(
    (v) => {
      if (!v.milestones.length) return true;
      const total = v.milestones.reduce((sum, m) => sum + m.weight_pct, 0);
      // Allow all-zero (even weighting fallback) OR total exactly 100.
      return total === 0 || total === 100;
    },
    {
      path: ["milestones"],
      message: "Milestone weights must sum to 100% (or leave all at 0 for even weighting).",
    },
  );
export type CreateProjectInput = z.infer<typeof createProjectSchema>;

// ---------------------------------------------------------------------------
// Update (partial) — mirrors base without the milestones bundle.
// ---------------------------------------------------------------------------

export const updateProjectSchema = projectBaseSchema
  .omit({ milestones: true })
  .partial()
  .extend({ id: uuidSchema });
export type UpdateProjectInput = z.infer<typeof updateProjectSchema>;

// ---------------------------------------------------------------------------
// Assignment schemas (rules §7).
// ---------------------------------------------------------------------------

export const PM_ASSIGNMENT_ROLES = ["PRIMARY_PM", "CO_PM"] as const;
export const pmAssignmentRoleSchema = z.enum(PM_ASSIGNMENT_ROLES);

export const createPmAssignmentSchema = z.object({
  project_id: uuidSchema,
  pm_employee_id: uuidSchema,
  assignment_role: pmAssignmentRoleSchema.default("PRIMARY_PM"),
});
export type CreatePmAssignmentInput = z.infer<typeof createPmAssignmentSchema>;

export const createEmployeeAssignmentSchema = z.object({
  project_id: uuidSchema,
  employee_id: uuidSchema,
  allocation_percentage: z
    .number()
    .int("Allocation percentage must be a whole number.")
    .min(1, "Allocation must be at least 1%.")
    .max(100, "Allocation cannot exceed 100%."),
});
export type CreateEmployeeAssignmentInput = z.infer<
  typeof createEmployeeAssignmentSchema
>;

// ---------------------------------------------------------------------------
// Budget (rules §7).
// ---------------------------------------------------------------------------

export const upsertProjectBudgetSchema = z.object({
  project_id: uuidSchema,
  budget_amount_idr: z
    .number()
    .int("Budget must be a whole rupiah amount.")
    .nonnegative("Budget cannot be negative."),
});
export type UpsertProjectBudgetInput = z.infer<typeof upsertProjectBudgetSchema>;

// ---------------------------------------------------------------------------
// Business Case (rules §6, §7 — Fase 1 lifecycle).
// ---------------------------------------------------------------------------

/**
 * Patch the BC block on a DRAFT-stage project. Used by OM / ADMIN to
 * flesh out the intake summary before promoting to PLANNING. Fields
 * are all optional so callers can save incrementally.
 */
export const updateProjectBusinessCaseSchema = z.object({
  id: uuidSchema,
  bc_executive_summary: z
    .string()
    .trim()
    .max(4000)
    .optional()
    .transform((v) => (v ? v : undefined)),
  bc_target_gm_pct: z
    .number()
    .min(0, "Target margin cannot be negative.")
    .max(100, "Target margin cannot exceed 100.")
    .optional(),
  bc_sponsor_id: uuidSchema.optional(),
});
export type UpdateProjectBusinessCaseInput = z.infer<
  typeof updateProjectBusinessCaseSchema
>;

/**
 * Promote a project from DRAFT (BC intake) to PLANNING (budget draft
 * phase). Requires all three BC fields to be non-empty at the DB level
 * — validated inside the action, not the schema, because we need to
 * read the current row to know what's missing.
 */
export const promoteProjectFromBusinessCaseSchema = z.object({
  id: uuidSchema,
});
export type PromoteProjectFromBusinessCaseInput = z.infer<
  typeof promoteProjectFromBusinessCaseSchema
>;

/**
 * Activate a PLANNING project. Caller (OM / ADMIN) must supply the
 * PRIMARY_PM assignment id. The action validates: (a) project status
 * is PLANNING, (b) at least one budget row is APPROVED, and (c) the
 * chosen PM has an eligible role. On success it inserts a
 * `project_pm_assignments` row and flips the project to ACTIVE inside
 * a single request (best-effort atomicity via compensating delete).
 */
export const activateProjectSchema = z.object({
  id: uuidSchema,
  pm_employee_id: uuidSchema,
});
export type ActivateProjectInput = z.infer<typeof activateProjectSchema>;
