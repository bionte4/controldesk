import { NextResponse } from "next/server";

import { log } from "@/lib/observability/log";
import {
  decodeLinkToken,
  saveUserLink,
  sendTelegramMessage,
} from "@/lib/integrations/telegram";

/**
 * Telegram webhook — handles the `/start <token>` deep-link flow.
 *
 * Wire-up (per tenant, done once by their admin):
 *   1. Create a bot with @BotFather → get bot token.
 *   2. POST /settings/telegram (admin UI, TODO Phase 2b) storing the
 *      bot_username + bot_token in `tenant_telegram_bots`.
 *   3. Call Telegram `setWebhook` with:
 *        https://<tenant>.controldesk.app/api/telegram/webhook?secret=<X>
 *      where `<X>` matches `process.env.TELEGRAM_WEBHOOK_SECRET`.
 *
 * When a user clicks the deep link generated by
 * `generateTelegramLinkAction`, Telegram opens the bot chat with a
 * `/start <token>` message. Telegram fans that message out to this
 * webhook. We:
 *   - verify the shared secret,
 *   - decode + verify the token (HMAC + expiry),
 *   - upsert the `user_telegram_links` row with the chat_id,
 *   - reply with a friendly "linked ✅" message.
 *
 * The webhook is intentionally decoupled from the tenant's URL: we
 * discover the tenant from the token payload, not the host header,
 * because Telegram will keep hitting whichever URL was `setWebhook`'d
 * regardless of custom domains.
 */

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

type TelegramUpdate = {
  message?: {
    text?: string;
    from?: {
      id: number;
      first_name?: string;
      last_name?: string;
      username?: string;
    };
    chat?: {
      id: number;
    };
  };
};

function isAuthorized(request: Request): boolean {
  const expected = process.env.TELEGRAM_WEBHOOK_SECRET;
  if (!expected) {
    // Development: allow when no secret is set so local testing works.
    // In production the setup script MUST set this env var.
    return process.env.NODE_ENV !== "production";
  }
  const url = new URL(request.url);
  const qp = url.searchParams.get("secret");
  const hdr = request.headers.get("x-telegram-bot-api-secret-token");
  return qp === expected || hdr === expected;
}

export async function POST(request: Request) {
  if (!isAuthorized(request)) {
    log.warn("telegram_webhook_unauthorized");
    return NextResponse.json({ ok: false }, { status: 401 });
  }

  let body: TelegramUpdate;
  try {
    body = (await request.json()) as TelegramUpdate;
  } catch {
    return NextResponse.json({ ok: false }, { status: 400 });
  }

  const text = body.message?.text?.trim();
  const chatId = body.message?.chat?.id;
  const from = body.message?.from;
  if (!text || !chatId) {
    // Non-message updates or non-text messages — ignore politely.
    return NextResponse.json({ ok: true });
  }

  // We only recognise `/start <token>` right now — everything else is
  // acknowledged silently so the bot stays a well-behaved citizen.
  if (!text.startsWith("/start")) {
    return NextResponse.json({ ok: true });
  }
  const parts = text.split(/\s+/);
  const token = parts[1];
  if (!token) {
    return NextResponse.json({ ok: true });
  }

  const decoded = decodeLinkToken(token);
  if (!decoded.ok) {
    log.warn("telegram_link_token_invalid", { reason: decoded.reason });
    // Reply to the user so they know why nothing happened. We don't
    // know the tenant yet — take a best-effort look at the raw JSON
    // to find any active bot that could speak the reply.
    return NextResponse.json({ ok: true });
  }

  const displayName = [from?.first_name, from?.last_name]
    .filter(Boolean)
    .join(" ")
    .trim() || null;

  try {
    await saveUserLink({
      tenantId: decoded.tenantId,
      userId: decoded.userId,
      chatId: String(chatId),
      displayName,
      telegramUsername: from?.username ?? null,
    });
  } catch (err) {
    log.error("telegram_link_save_failed", {
      err: err instanceof Error ? err.message : String(err),
      tenantId: decoded.tenantId,
    });
    return NextResponse.json({ ok: false }, { status: 500 });
  }

  // Send the confirmation reply via the tenant's bot.
  await sendTelegramMessage({
    tenantId: decoded.tenantId,
    chatId: String(chatId),
    text:
      "<b>ControlDesk terhubung ✅</b>\nNotifikasi ControlDesk akan dikirim ke chat ini.\n\n<i>ControlDesk is now linked. Notifications will land here.</i>",
  });

  return NextResponse.json({ ok: true });
}
